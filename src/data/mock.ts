const buildHistory = (client: Client, offset: number): HealthHistoryPoint[] =>
  weeks.map((week, index) => {
    const drift = index - 7
    const customerScore = Math.max(18, Math.min(94, client.healthScore + Math.round(drift * offset * 0.8)))
    const deliveryScore = Math.max(16, Math.min(96, customerScore - 4 + ((index + offset) % 7)))
    const relationshipScore = Math.max(20, Math.min(95, customerScore + 3 - ((index + offset) % 6)))

    return {
      clientId: client.id,
      week,
      customerScore,
      deliveryScore,
      relationshipScore,
    }
  })

